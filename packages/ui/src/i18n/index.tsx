const messages: Record<Locale, Messages> = { en: enMessages, vi: viMessages }

const STORAGE_KEY = 'fquiz-locale'
const DEFAULT_LOCALE_CONTEXT = { locale: 'en' as Locale, setLocale: (_locale: Locale) => {} }
const LocaleContext = createContext(DEFAULT_LOCALE_CONTEXT)

function isLocale(value: string | null): value is Locale {
  return value !== null && SUPPORTED_LOCALES.includes(value as Locale)
}

export function LocaleProvider({ children, initialLocale = 'vi' }: {
  children: React.ReactNode
  initialLocale?: Locale
}) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale)
  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale)
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(STORAGE_KEY, nextLocale)
      document.cookie = `${STORAGE_KEY}=${nextLocale}; path=/; max-age=31536000; samesite=lax`
    }
  }, [])

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY)
    if (isLocale(saved)) setLocaleState(saved)
  }, [])

  useEffect(() => {
    document.documentElement.lang = locale
    window.localStorage.setItem(STORAGE_KEY, locale)
    document.cookie = `${STORAGE_KEY}=${locale}; path=/; max-age=31536000; samesite=lax`
  }, [locale])

  const value = useMemo(() => ({
    locale,
    setLocale,
  }), [locale, setLocale])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  return useContext(LocaleContext)
}

export function useTranslations() {
  const { locale } = useLocale()
  return useCallback((key: keyof typeof messages.en, values?: TranslationValues) => translateMessage(locale, key, values), [locale])
}

export function translateMessage(locale: Locale, key: keyof typeof messages.en, values?: TranslationValues) {
  const message = messages[locale][key] ?? messages.en[key]
  return values ? message.replace(/\{\{(\w+)\}\}/g, (_match, name: string) => String(values[name] ?? '')) : message
}

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'vi'
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    return isLocale(stored) ? stored : 'vi'
  } catch {
    return 'vi'
  }
}

